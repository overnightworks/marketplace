// The lane runs as one workflow script, because the Workflow runtime snapshots only the script a run starts with:
// a part resolved by name mid-run could come from another release after a /reload-plugins. This bundles the
// sources under plugins/atelier/lane/ into plugins/atelier/workflows/lane.js; --check fails on any difference.
import fs from 'node:fs'
import { fileURLToPath, pathToFileURL } from 'node:url'

const SOURCES = new URL('../plugins/atelier/lane/', import.meta.url)
const BUNDLE = new URL('../plugins/atelier/workflows/lane.js', import.meta.url)
const COMMAND = 'node scripts/build_lane.mjs'
const HEADER = `// Generated by \`${COMMAND}\` from plugins/atelier/lane/; edit the sources there and regenerate, never this file.\n`
// The script's meta comes first, the parts follow, and the main body last: it ends in top-level returns.
const META_MODULE = 'meta.js'
const MAIN_MODULE = 'main.js'
const EXPORTED_FUNCTION = /^export (async function )/gm

const read = (name) => fs.readFileSync(new URL(name, SOURCES), 'utf8')

/** The bundled lane script built from the source modules. */
export function renderLane() {
  const parts = fs.readdirSync(SOURCES).filter(name => name.endsWith('.js') && ![META_MODULE, MAIN_MODULE].includes(name)).sort()
  return [HEADER + read(META_MODULE), ...parts.map(name => read(name).replace(EXPORTED_FUNCTION, '$1')), read(MAIN_MODULE)].join('\n')
}

function main(argv) {
  const rendered = renderLane()
  if (!argv.includes('--check')) return fs.writeFileSync(BUNDLE, rendered)
  if (fs.readFileSync(BUNDLE, 'utf8') === rendered) return
  console.error(`${fileURLToPath(BUNDLE)} differs from its sources; run \`${COMMAND}\` and commit the result`)
  process.exitCode = 1
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) main(process.argv.slice(2))
